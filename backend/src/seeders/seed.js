const seed = async () => {
  console.log('🌱 Connecting to MongoDB:', MONGODB_URI);
  await mongoose.connect(MONGODB_URI);
  console.log('✅ Connected');

  // Hotels
  console.log('\n🏨 Seeding hotels...');
  await Hotel.deleteMany({});
  await Hotel.insertMany(HOTELS);
  console.log(`   ✅ ${HOTELS.length} hotels seeded`);

  // Admin users — hash passwords and PINs manually since insertMany skips hooks
  console.log('\n👤 Seeding admin users...');
  await AdminUser.deleteMany({});
  for (const admin of ADMIN_USERS) {
    const existing = await AdminUser.findOne({ email: admin.email });
    if (!existing) {
      await AdminUser.create(admin); // uses pre-save hook for hashing
    }
  }
  console.log(`   ✅ ${ADMIN_USERS.length} admin users seeded`);

  // Offers
  console.log('\n🎫 Seeding offers...');
  await Offer.deleteMany({});
  await Offer.insertMany(OFFERS);
  console.log(`   ✅ ${OFFERS.length} offers seeded`);

  console.log('\n🎉 Seed complete!\n');
  console.log('Admin login credentials:');
  ADMIN_USERS.forEach(a => {
    console.log(`   ${a.role.padEnd(15)} | ${a.email.padEnd(35)} | password: StayEase@Enterprise2026 | PIN: ${a.pin}`);
  });

  await mongoose.disconnect();
  process.exit(0);
};

seed().catch(err => {
  console.error('❌ Seed failed:', err);
  process.exit(1);
});
